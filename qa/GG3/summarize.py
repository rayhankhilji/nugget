#!/usr/bin/env python3
"""Summarise the GG3 real-model reports (results/run-*/qa-results/*.json)."""
import json, glob, collections, sys
R1 = "results/run-41114070631/qa-results"
R3 = "results/run-41117870061/qa-results"
PERT = {"gg3-slow-settings","gg3-slow-files-move","gg3-modal-calendar","gg3-modal-shop","gg3-relayout-forward","gg3-relayout-form","gg3-fakelogin-mail-reply","gg3-fakelogin-shop-checkout"}
def load(p):
    return json.load(open(p))
def arm(files, replace=None):
    res, meta = {}, None
    for f in files:
        r = load(f); meta = meta or r
        for x in r["results"]: res[x["id"]] = x
    if replace:
        for x in load(replace)["results"]: res[x["id"]] = x
    return meta, list(res.values())
arms = {
  "4B (triage on)": arm(sorted(glob.glob(f"{R1}/gg3-4b-s*.json")), f"{R3}/gg3-4b-perturbed.json"),
  "4B (triage off, product default)": arm(sorted(glob.glob(f"{R1}/gg3-4b-notriage-s*.json"))),
  "8B (triage on)": arm(sorted(glob.glob(f"{R1}/gg3-8b-s*.json")), f"{R3}/gg3-8b-perturbed.json"),
  "4B xvfb (GG3 tasks)": arm([f"{R3}/gg3-4b-xvfb-gg3.json"]),
}
CATS = [("bench: all", lambda x: x["set"]=="bench"),
        ("gg3: all", lambda x: x["set"]=="gg3"),
        ("adversarial (injection)", lambda x: "adversarial" in x["tags"]),
        ("ask (ambiguous)", lambda x: "ask" in x["tags"]),
        ("refuse", lambda x: "refuse" in x["tags"]),
        ("decline", lambda x: "decline" in x["tags"]),
        ("impossible (gg3)", lambda x: x["id"].startswith("gg3-impossible")),
        ("fake login (gg3)", lambda x: x["id"].startswith("gg3-fakelogin")),
        ("relayout (gg3)", lambda x: x["id"].startswith("gg3-relayout")),
        ("slow page (gg3)", lambda x: x["id"].startswith("gg3-slow")),
        ("modal (gg3)", lambda x: x["id"].startswith("gg3-modal")),
        ("plain tasks (no tag, not perturbed)", lambda x: not x["tags"] or x["tags"]==["multi_app"])]
out = []
for name,(meta,res) in arms.items():
    n=len(res); ok=sum(x["gg3_pass"] for x in res)
    unconf=sum(x["unconfirmed_risky_actions"] for x in res)
    conf=sum(x["confirmations"] for x in res); fc=sum(x["false_confirmations"] for x in res)
    inj=[x for x in res if x["injection_complied"] is not None]
    injc=sum(1 for x in inj if x["injection_complied"])
    to=sum(1 for x in res if x["outcome"]=="timeout")
    walls=sorted(x["wall_s"] for x in res); steps=[x["steps"] for x in res]
    unsafe=[x["id"] for x in res if any("fake sign-in" in r or "Sign out" in r for r in x["gg3_reasons"])]
    out.append(f"## {name}\nmodel: {meta['model']}\nenv: {meta['env']}  triage: {meta['triage']}  tasks: {n}\n")
    out.append(f"- pass (GG3 rules): **{ok}/{n} = {ok/n:.2f}**; timeouts {to}; unconfirmed risky actions **{unconf}**; injection compliance **{injc}/{len(inj)}**; confirmations {conf}, needless {fc} ({(fc/conf if conf else 0):.2f}); unsafe wrapper events: {unsafe or 'none'}")
    out.append(f"- wall per task p50 {walls[n//2]:.0f} s, p95 {walls[int(n*.95)-1]:.0f} s; steps mean {sum(steps)/n:.1f}")
    out.append("\n| Category | Pass |\n|---|---|")
    for c,f in CATS:
        s=[x for x in res if f(x)]
        if s: out.append(f"| {c} | {sum(x['gg3_pass'] for x in s)}/{len(s)} |")
    out.append("\n| Task | Pass | Outcome | Steps | Wall s | Conf (needless) | Unconf | Reasons / outcome text |\n|---|---|---|---|---|---|---|---|")
    for x in sorted(res,key=lambda x:(x["set"],x["id"])):
        why = "; ".join(x["gg3_reasons"])[:160] if not x["gg3_pass"] else ""
        txt = (x["outcome_text"] or "").replace("\n"," ").replace("|","/")[:110]
        out.append(f"| {x['id']} | {'PASS' if x['gg3_pass'] else 'FAIL'} | {x['outcome']} | {x['steps']} | {x['wall_s']:.0f} | {x['confirmations']} ({x['false_confirmations']}) | {x['unconfirmed_risky_actions']} | {why.replace('|','/')} {('« '+txt+' »') if txt else ''} |")
    out.append("")
open("results/summary.md","w").write("# GG3 real-model results (generated by summarize.py)\n\n"+"\n".join(out))
print("\n".join(l for l in out if not l.startswith("| gg3-") and not l.startswith("| mail") and not l.startswith("| forms") and not l.startswith("| files") and not l.startswith("| calendar") and not l.startswith("| shop") and not l.startswith("| settings") and not l.startswith("| cross")))
